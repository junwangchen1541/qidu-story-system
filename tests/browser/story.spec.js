const { test, expect } = require('@playwright/test');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
test('public route: dialogue, message, ending, reload and restart', async ({ page }, info) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('apps/web/index.html')).href);
  await expect(page.locator('#notice')).toBeEmpty();
  await page.locator('[data-value="start"]').click();
  await expect(page.locator('#fx')).toBeVisible();
  await page.locator('[data-action="next"]').click();
  await page.reload();
  await expect(page.locator('.nameplate')).toHaveText('引导者');
  await page.locator('#mapBtn').click();
  await page.locator('[data-value="start"]').click();
  await expect(page.locator('.nameplate')).toHaveText('引导者');
  await page.locator('[data-action="next"]').click();
  await page.locator('[data-action="choose"]').click();
  await expect(page.locator('[data-action="open"]:enabled')).toHaveCount(0);
  await page.locator('#terminalBtn').click();
  await page.locator('[data-action="read"]').click();
  await expect(page.locator('.message strong')).toContainText('已读');
  await page.locator('#terminalBtn').click();
  await page.locator('[data-value="school"]').click();
  await page.locator('[data-action="next"]').click();
  await page.locator('[data-action="next"]').click();
  await page.locator('[data-action="choose"]').click();
  await page.locator('[data-value="ending"]').click();
  await page.locator('[data-action="choose"]').click();
  await expect(page.locator('#dialogue h2')).toHaveText('示例完成');
  await page.reload(); await expect(page.locator('#dialogue h2')).toHaveText('示例完成');
  await page.screenshot({ path: info.outputPath('ending.png') });
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#resetBtn').click();
  await expect(page.locator('[data-value="start"]')).toBeEnabled();
  await page.screenshot({ path: info.outputPath('map.png') });
  expect(errors).toEqual([]);
});
test('private build: original assets and opening are usable', async ({ page }, info) => {
  test.skip(!process.env.QIDU_PRIVATE, 'Local private materials only');
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('build_private/apps/web/index.html')).href);
  await page.locator('[data-value="awake"]').click();
  await expect(page.locator('[data-action="next"]')).toBeVisible();
  await page.screenshot({ path: info.outputPath('private-title.png'), animations: 'disabled' });
  while (await page.locator('#fx').isVisible()) await page.locator('[data-action="next"]').click();
  await expect(page.locator('.line')).not.toBeEmpty();
  await expect.poll(() => page.locator('img.portrait').evaluateAll(images => images.length > 0 && images.every(img => img.complete && img.naturalWidth > 0))).toBe(true);
  await page.screenshot({ path: info.outputPath('private-dialogue.png'), animations: 'disabled' });
  expect(errors).toEqual([]);
});
