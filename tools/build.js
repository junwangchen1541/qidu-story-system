const fs = require("node:fs");
const path = require("node:path");
const core = require("../packages/story-core");
const root = path.resolve(__dirname, "..");
function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text, "utf8");
}
function contentSource(content, web) {
  return "// Generated by tools/build.js; edit data/routes or private source instead.\n" +
    (web ? "window.StoryContent = " : "module.exports = ") + JSON.stringify(content, null, 2) + ";\n";
}
function copyTree(source, destination, filter = () => true) {
  if (!filter(source)) return;
  if (fs.statSync(source).isDirectory()) {
    fs.mkdirSync(destination, { recursive: true });
    for (const name of fs.readdirSync(source)) copyTree(path.join(source, name), path.join(destination, name), filter);
  } else {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, fs.readFileSync(source));
  }
}
function buildAt(destination, route, assets = { bg: {}, portrait: {}, audio: {} }) {
  const validation = core.validateRoute(route);
  if (!validation.ok) throw new Error(validation.errors.join("\n"));
  const wechat = path.join(destination, "apps/wechat");
  if (destination !== root) {
    // Only source app files are copied; local settings and generated content are excluded.
    for (const app of ["web", "wechat"]) {
      copyTree(path.join(root, "apps", app), path.join(destination, "apps", app),
        (file) => !/project\.(private|local)\.config\.json$|[/\\](shared|data|content\.js)$/.test(file));
    }
    fs.mkdirSync(path.join(destination, "packages"), { recursive: true });
    copyTree(path.join(root, "packages/story-core"), path.join(destination, "packages/story-core"));
  }
  const shared = path.join(wechat, "shared");
  fs.mkdirSync(shared, { recursive: true });
  for (const name of ["index.js", "session.js"]) {
    fs.copyFileSync(path.join(root, "packages/story-core", name), path.join(shared, name));
  }
  write(path.join(destination, "apps/web/content.js"), contentSource({ route, assets }, true));
  const miniAssets = Object.fromEntries(Object.entries(assets).map(([kind, entries]) =>
    [kind, Object.fromEntries(Object.entries(entries).map(([key, url]) => [key, url.replace(/^\.\/assets\//, "/assets/")]))]));
  write(path.join(wechat, "data/content.js"), contentSource({ route, assets: miniAssets }, false));
  // Remove only obsolete generated files from the first migration iteration.
  for (const file of ["shared/story-core.js", "data/public-demo.json"]) {
    const target = path.join(wechat, file);
    if (fs.existsSync(target)) fs.unlinkSync(target);
  }
}
function buildPublic() {
  const route = JSON.parse(fs.readFileSync(path.join(root, "data/routes/public-demo.json"), "utf8"));
  buildAt(root, route);
  console.log("Built public Web + WeChat from one route and core.");
}
if (require.main === module) buildPublic();
module.exports = { root, write, copyTree, buildAt, buildPublic, contentSource };
